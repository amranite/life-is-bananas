package com.lifeisbananas.model.enums;

/**
 * Enumeration representing different units of measurement used in formulas.
 * Used for specifying quantities of ingredients and raw materials.
 */

public enum UnitType {
    GRAM, // Grams - used for small quantities
    KILOGRAM, // Kilograms - used for larger quantities
    MILLILITER, // Milliliter - used for liquid measurements
    PERCENTAGE, // Percentage - used for ratio based measurements
    PIECE // Piece - used for countable items
}
