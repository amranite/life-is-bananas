package com.lifeisbananas.model.bioengineer;

import com.lifeisbananas.model.formula.Formula;
import com.lifeisbananas.model.product.Product;
import com.lifeisbananas.model.instruction.FreezeDryInstruction;
import java.util.ArrayList;
import java.util.List;

/**
 * Represents a food scientist (bio-engineer) specialized in food technology.
 * Bio-engineers are responsible for developing new healthy freeze-dried snacks,
 * creating formulas, developing products, and generating freeze-drying instructions.
 */

@SuppressWarnings("unused") // This annotation is to get rid of the "is never used" warnings
public class BioEngineer {

    // The id of the bio-engineer
    private int id;

    // Full name of the bio-engineer
    private String name;

    // Email address for contact
    private String email;

    // Phone number for contact
    private String phoneNumber;

    // Area of specialization (e.g., "Fruit Processing", "Nutritional Science")
    private String specialization;

    /**
     * Formulas created by this bio-engineer.
     * One-to-many relationship: one engineer creates many formulas.
     */
    private List<Formula> formulas = new ArrayList<>();

    /**
     * Products developed by this bio-engineer.
     * One-to-many relationship: one engineer develops many products.
     */
    private List<Product> products = new ArrayList<>();

    /**
     * Freeze-dry instructions generated by this bio-engineer.
     * One-to-many relationship: one engineer can generate multiple instructions.
     */
    private List<FreezeDryInstruction> freezeDryInstructions = new ArrayList<>();

    // --- Constructors ---

    // Default constructor for JPA
    public BioEngineer() {
    }

    // Constructor with essential fields
    public BioEngineer(String name, String email, String phoneNumber, String specialization) {
        this.name = name;
        this.email = email;
        this.phoneNumber = phoneNumber;
        this.specialization = specialization;
    }

    // --- Business Methods ---

    /**
     * Creates and adds a new formula to this bio-engineer's portfolio
     * @param formula the formula to be created
     * @return the created formula
     */
    public Formula createFormula(Formula formula) {
        formula.setBioEngineer(this);
        this.formulas.add(formula);
        return formula;
    }

    /**
     * Develops and adds a new product to this bio-engineer's portfolio
     * @param product the product to be developed
     * @return the developed product
     */
    public Product developProduct(Product product) {
        product.setBioEngineer(this);
        this.products.add(product);
        return product;
    }

    /**
     * Generates and adds a new freeze-dry instruction
     * @param instruction the instruction to be generated
     * @return the generated instruction
     */
    public FreezeDryInstruction generateFreezeDryInstruction(FreezeDryInstruction instruction) {
        instruction.setBioEngineer(this);
        this.freezeDryInstructions.add(instruction);
        return instruction;
    }

    // --- Getters and Setters ---

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhoneNumber() {
        return phoneNumber;
    }

    public void setPhoneNumber(String phoneNumber) {
        this.phoneNumber = phoneNumber;
    }

    public String getSpecialization() {
        return specialization;
    }

    public void setSpecialization(String specialization) {
        this.specialization = specialization;
    }

    public List<Formula> getFormulas() {
        return formulas;
    }

    public void setFormulas(List<Formula> formulas) {
        this.formulas = formulas;
    }

    public List<Product> getProducts() {
        return products;
    }

    public void setProducts(List<Product> products) {
        this.products = products;
    }

    public List<FreezeDryInstruction> getFreezeDryInstructions() {
        return freezeDryInstructions;
    }

    public void setFreezeDryInstructions(List<FreezeDryInstruction> freezeDryInstructions) {
        this.freezeDryInstructions = freezeDryInstructions;
    }
}
